const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.UI_PLAYWRIGHT_PATH || 'playwright');
const root = path.resolve(__dirname, '..');
const base = process.env.UI_BASE || 'http://127.0.0.1:5184';
assert(['localhost', '127.0.0.1'].includes(new URL(base).hostname), 'Only loopback verification is supported');
const output = path.join(root, 'docs/evidence/project-template-creation');
fs.mkdirSync(output, { recursive: true });
const credentials = JSON.parse(fs.readFileSync(path.join(root, '.local-secrets/admin-credentials.json'), 'utf8')).accounts.local;
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.UI_CHROMIUM_PATH, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const api = async (endpoint, method = 'GET', body) => page.evaluate(async ({ endpoint, method, body }) => {
    const result = await fetch(`/api/v1${endpoint}`, { method, credentials: 'include', headers: { 'Content-Type': 'application/json', 'Idempotency-Key': crypto.randomUUID() }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    if (!result.ok) throw new Error(`${method} ${endpoint}: ${result.status}`);
    return (await result.json()).data;
  }, { endpoint, method, body });
  try {
    await page.goto(`${base}/login`, { waitUntil: 'networkidle' });
    await page.getByLabel(/用户名或邮箱/).fill(credentials.username);
    await page.getByLabel('密码').fill(credentials.password);
    await page.getByRole('button', { name: '登录工作区', exact: true }).click();
    await page.waitForURL(/\/app$/);
    const count = (await api('/projects?status=all&limit=100')).items.length;
    await page.goto(`${base}/app/projects/new`, { waitUntil: 'networkidle' });
    await page.getByRole('link', { name: '分步创建', exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, '01-mode-choice.png'), fullPage: true });
    await page.getByRole('button', { name: '选择模板', exact: true }).click();
    await page.getByRole('button', { name: '使用空项目模板', exact: true }).click();
    await page.waitForURL(/\/new\/template\/[a-f0-9-]+$/);
    const draftId = new URL(page.url()).pathname.split('/').pop();
    await page.getByLabel('项目名称', {exact:true}).fill('空模板浏览器验收');
    await page.getByLabel('项目说明').fill('先编辑私有预览，最后才正式创建。');
    await page.getByRole('button', { name: '任务', exact: true }).click();
    await page.getByLabel('项目主目标（可选）').fill('形成可复核成果');
    await page.getByRole('button', { name: /添加子任务/ }).click();
    await page.getByLabel('子任务标题').fill('完成验证');
    await page.getByLabel('验收标准').fill('提供验证记录');
    await page.getByRole('button', { name: '资料', exact: true }).click();
    await page.getByRole('button', { name: /新建文档/ }).click();
    await page.getByLabel('文档标题').fill('预览成果');
    await page.getByLabel('文档正文（Markdown）').fill('# 可复核成果\n\n保存前尚无正式项目。');
    await page.getByRole('button', { name: '保存草稿', exact: true }).click();
    await page.getByText('私有草稿已保存，尚未创建正式项目。', { exact: true }).waitFor();
    assert.equal((await api('/projects?status=all&limit=100')).items.length, count);
    await page.screenshot({ path: path.join(output, '02-draft-desktop.png'), fullPage: true });
    await page.reload({ waitUntil: 'networkidle' });
    await page.getByRole('button', { name: '任务', exact: true }).click();
    assert.equal(await page.getByLabel('子任务标题').inputValue(), '完成验证');
    const restored = await api(`/creation-drafts/${draftId}`);
    assert.equal(restored.payload.workspace.materials[0].title, '预览成果');
    assert.equal(restored.preview.tasks.length, 1);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, '03-draft-mobile.png'), fullPage: true });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'Mobile preview must fit viewport');
    await page.getByRole('button', { name: '保存并创建项目', exact: true }).click();
    await page.waitForURL(/\/app\/projects\/[a-f0-9-]+$/);
    const projectId = new URL(page.url()).pathname.split('/').pop();
    assert.equal((await api('/projects?status=all&limit=100')).items.length, count + 1);
    assert.equal((await api(`/projects/${projectId}/goal`)).title, '形成可复核成果');
    assert.equal((await api(`/projects/${projectId}/tasks`)).items.length, 1);
    assert((await api(`/projects/${projectId}/resource-library`)).items.some(item => item.title === '预览成果'));
    assert.deepEqual(errors, []);
    const project = await api(`/projects/${projectId}`);
    await api(`/projects/${projectId}`, 'PATCH', { expectedRevision: project.revision, status: 'archived' });
    fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify({ status: 'passed', checkedAt: new Date().toISOString(), draftId, projectId, checks: ['two creation modes', 'blank template', 'private five-section workspace', 'goal/task/document edits', 'draft refresh recovery', 'no formal project before commit', 'atomic final project', '390px layout'], browserErrors: errors }, null, 2));
    console.log('PASS: real desktop/mobile template flow; choice, private preview/edit/save/refresh, final formal project and preserved authored contents.');
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'error-state.png'), fullPage: true }).catch(() => {});
    console.error(`Template UI failed at ${new URL(page.url()).pathname}: ${error.message}`);
    process.exitCode = 1;
  } finally { await browser.close(); }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
