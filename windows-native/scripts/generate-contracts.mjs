import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export function inventory(spec) {
  return Object.entries(spec.paths).flatMap(([url, methods]) => Object.entries(methods)
    .filter(([method]) => ['get', 'post', 'put', 'patch', 'delete', 'head', 'options'].includes(method))
    .map(([method, operation]) => ({ method: method.toUpperCase(), path: url, family: operation.tags?.[0] ?? 'other', summary: operation.summary ?? '',
      requestContentTypes: Object.keys(operation.requestBody?.content ?? {}), responseStatuses: Object.keys(operation.responses ?? {}) })))
    .sort((a, b) => a.path.localeCompare(b.path, 'en') || a.method.localeCompare(b.method, 'en'));
}

export function generate(root, check = false) {
  const operations = inventory(JSON.parse(fs.readFileSync(path.join(root, 'backend/openapi/openapi.json'), 'utf8')));
  const families = Object.fromEntries([...new Set(operations.map(x => x.family))].sort().map(family => [family, operations.filter(x => x.family === family).map(x => `${x.method} ${x.path}`)]));
  const outputs = {
    'windows-native/docs/operation-inventory.json': JSON.stringify({ notice: 'API inventory only. Does not establish native UI implementation or acceptance.', operations }, null, 2) + '\n',
    'windows-native/scripts/generated-routes.mjs': '// Generated by generate-contracts.mjs; API contracts are not UI parity evidence.\nexport const routeFamilies = Object.freeze(' + JSON.stringify(families, null, 2) + ');\n',
  };
  for (const [name, source] of Object.entries(outputs)) {
    const target = path.join(root, name);
    if (check) { if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source) throw new Error(`Stale contract inventory: ${name}`); }
    else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, source); }
  }
  return operations.length;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  console.log(`${generate(root, process.argv.includes('--check'))} Windows API operations verified; UI parity is assessed separately.`);
}
